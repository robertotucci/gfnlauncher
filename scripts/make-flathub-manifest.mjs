#!/usr/bin/env node
//
// Builds the Flathub submission from flatpak/io.github.robertotucci.GfnLauncher.yml.
//
// The manifest in flatpak/ builds the working tree, which is what makes
// `npm run flatpak:build` test the code in front of you. Flathub cannot: its
// builders have no working tree and no network, so the same manifest has to
// name a pinned checkout instead. That one source is the only difference
// between the two files, and this script is what swaps it — by text, so every
// comment in the manifest survives into the copy a Flathub reviewer reads.
//
//   node scripts/make-flathub-manifest.mjs [--tag vX.Y.Z] [--out DIR]
//
// Defaults to the tag matching package.json and release/flathub/. Writes the
// three files a submission needs beside each other: the manifest, flathub.json,
// and generated-sources.json, which the manifest includes by a path relative to
// itself and therefore has to travel with it.

import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const APP_ID = 'io.github.robertotucci.GfnLauncher'
const REPO_URL = 'https://github.com/robertotucci/gfnlauncher.git'

const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim()

function parseArgs(argv) {
  const args = { tag: null, out: null }
  for (let i = 0; i < argv.length; i++) {
    const next = () => {
      const value = argv[i + 1]
      if (value === undefined) throw new Error(`${argv[i]} needs a value`)
      i++
      return value
    }
    if (argv[i] === '--tag') args.tag = next()
    else if (argv[i] === '--out') args.out = next()
    else throw new Error(`Unknown argument: ${argv[i]}`)
  }
  return args
}

// Replaces the `type: dir` source, and the comment block above it, with a git
// source pinned to `tag` at `commit`. By text rather than through a YAML
// round-trip, which would strip every comment in the file — including the ones
// beside the permissions a Flathub reviewer is going to ask about, which are
// the reason those comments were written.
function pinSource(manifest, { tag, commit }) {
  const lines = manifest.split('\n')

  const entries = lines.reduce((found, line, i) => (line === '      - type: dir' ? [...found, i] : found), [])
  if (entries.length !== 1) {
    throw new Error(`Expected exactly one \`type: dir\` source in the manifest, found ${entries.length}`)
  }
  const [entry] = entries

  // Backwards over the comment block introducing the source, so the replacement
  // does not leave a paragraph describing a source that is no longer there.
  let start = entry
  while (start > 0 && lines[start - 1].startsWith('      #')) start--

  // Forwards over the entry's own keys, which are indented past the `- `. Stops
  // at the blank line before the next source.
  let end = entry + 1
  while (end < lines.length && lines[end].startsWith('        ')) end++

  const replacement = [
    '      # The release tag, pinned. The manifest in the application repository',
    '      # builds the working tree instead; that source is the only difference',
    '      # between the two, and scripts/make-flathub-manifest.mjs is what swaps',
    '      # it.',
    '      #',
    '      # Both keys: the tag is what a reader checks against the release page,',
    '      # the commit is what keeps the build reproducible if that tag ever',
    '      # moves.',
    '      - type: git',
    `        url: ${REPO_URL}`,
    `        tag: ${tag}`,
    `        commit: ${commit}`,
  ]

  return [...lines.slice(0, start), ...replacement, ...lines.slice(end)].join('\n')
}

function header(tag) {
  return [
    `# ${APP_ID}`,
    '#',
    `# Generated by scripts/make-flathub-manifest.mjs from flatpak/${APP_ID}.yml`,
    `# at ${tag}. Edit it there and regenerate rather than here, so that the`,
    '# manifest this was built from stays the one that gets tested locally.',
    '',
    '',
  ].join('\n')
}

function main() {
  const args = parseArgs(process.argv.slice(2))

  const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version
  const tag = args.tag ?? `v${version}`
  const out = resolve(ROOT, args.out ?? 'release/flathub')

  // `^{commit}` dereferences an annotated tag, whose own object id is not what
  // a git source wants. A tag that does not exist fails here, loudly.
  const commit = git('rev-parse', '--verify', `${tag}^{commit}`)

  // Flathub fetches from the remote, not from this disk: a tag that exists only
  // locally builds here and 404s there.
  const remote = git('ls-remote', 'origin', `refs/tags/${tag}^{}`)
  if (!remote.startsWith(commit)) {
    throw new Error(
      `Tag ${tag} is ${commit} locally but ${remote ? remote.split('\t')[0] : 'absent'} on origin. ` +
        'Push the tag before generating a submission.',
    )
  }

  if (tag !== `v${version}`) {
    console.warn(`Warning: building ${tag} while package.json says ${version}.`)
  }

  const manifest = readFileSync(join(ROOT, 'flatpak', `${APP_ID}.yml`), 'utf8')

  mkdirSync(out, { recursive: true })
  writeFileSync(join(out, `${APP_ID}.yml`), header(tag) + pinSource(manifest, { tag, commit }))
  copyFileSync(join(ROOT, 'flatpak', 'flathub.json'), join(out, 'flathub.json'))
  copyFileSync(join(ROOT, 'flatpak', 'generated-sources.json'), join(out, 'generated-sources.json'))

  console.log(`Wrote ${out}`)
  console.log(`  ${APP_ID}.yml      ${tag} at ${commit.slice(0, 12)}`)
  console.log('  flathub.json')
  console.log('  generated-sources.json')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
